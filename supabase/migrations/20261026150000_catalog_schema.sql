-- IAR USA catalog schema: products, fault codes, quote requests.
-- Based on SUPABASE-RECOMMENDATION.md from the frontend sample pack.
-- Sized for ~1M products: all list/search paths are index-backed.

create extension if not exists pg_trgm with schema extensions;

-- Slug helper (immutable so it can back generated columns) -----------
create or replace function public.slugify(value text)
returns text
language sql
immutable
parallel safe
as $$
  select trim(both '-' from regexp_replace(lower(coalesce(value, '')), '[^a-z0-9]+', '-', 'g'))
$$;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

-- PRODUCTS ------------------------------------------------------------
create table public.products (
  id                 bigint generated by default as identity primary key,
  created_at         timestamptz not null default timezone('utc', now()),
  updated_at         timestamptz not null default timezone('utc', now()),
  slug               text unique not null,
  sku                text unique,
  part_number        text not null,
  manufacturer       text,
  brand              text,
  category           text,
  manufacturer_slug  text generated always as (public.slugify(manufacturer)) stored,
  category_slug      text generated always as (nullif(public.slugify(category), '')) stored,
  title              text,
  breadcrumb         text[],
  description        text,
  -- offer block
  price              numeric(12, 2),            -- null => quote-only
  currency           text not null default 'USD',
  price_display      text not null default 'Request Quote',
  condition          text default 'Refurbished',
  availability       text default 'InStock',
  price_valid_until  date,
  -- rating block (static trust element)
  rating_value       numeric(2, 1),
  review_count       int not null default 0,
  best_rating        int not null default 5,
  -- service details
  turnaround         text[],
  warranty           text,
  -- tabbed content
  tab_specifications text,
  tab_common_faults  jsonb not null default '[]'::jsonb,  -- [{fault, detail}]
  tab_repair_process jsonb not null default '[]'::jsonb,  -- [{step, detail}]
  tab_faq            jsonb not null default '[]'::jsonb,  -- [{question, answer}]
  -- media
  image_url          text,
  images             jsonb not null default '[]'::jsonb,
  -- provenance / enrichment tracking (never rendered)
  source             text,                      -- inventory | master | synchronics
  source_url         text,
  image_source       text,
  data_confidence    text,
  inventory_id       bigint,
  ebay_item_id       text,
  -- full-text search
  search             tsvector generated always as (
    setweight(to_tsvector('simple', coalesce(part_number, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(manufacturer, '')), 'B') ||
    setweight(to_tsvector('english', coalesce(title, '')), 'C') ||
    setweight(to_tsvector('english', coalesce(category, '')), 'C')
  ) stored
);

create index idx_products_part      on public.products (part_number);
create index idx_products_part_trgm on public.products using gin (part_number extensions.gin_trgm_ops);
create index idx_products_mfr       on public.products (manufacturer_slug, part_number);
create index idx_products_cat       on public.products (category_slug, part_number) where category_slug is not null;
create index idx_products_search    on public.products using gin (search);
create index idx_products_id_upd    on public.products (id) include (slug, updated_at);

create trigger trg_products_updated_at
  before update on public.products
  for each row execute function public.set_updated_at();

-- FAULT CODES ---------------------------------------------------------
create table public.fault_codes (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default timezone('utc', now()),
  updated_at        timestamptz not null default timezone('utc', now()),
  slug              text unique not null,
  title             text not null,
  description       text,
  severity          text,
  keywords          text,
  symptoms          text[],
  causes            text[],
  repair_steps      text[],
  affected_models   text[],
  manufacturer      text,
  manufacturer_slug text generated always as (public.slugify(manufacturer)) stored
);
create index idx_fault_mfr on public.fault_codes (manufacturer_slug);

create trigger trg_fault_codes_updated_at
  before update on public.fault_codes
  for each row execute function public.set_updated_at();

-- QUOTE REQUESTS ("Request Quote" CTA target) -------------------------
create table public.quote_requests (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default timezone('utc', now()),
  product_id  bigint references public.products (id) on delete set null,
  part_number text,
  name        text not null check (char_length(name) between 1 and 200),
  email       text not null check (char_length(email) between 3 and 320),
  phone       text check (char_length(phone) <= 50),
  company     text check (char_length(company) <= 200),
  quantity    int check (quantity between 1 and 100000),
  message     text check (char_length(message) <= 5000),
  status      text not null default 'new'
);
create index idx_quotes_created on public.quote_requests (created_at desc);

-- FACETS (manufacturer / category counts) -----------------------------
-- Materialized: GROUP BY over 1M rows is too slow per request.
-- Refresh after each bulk import: select public.refresh_catalog_facets();
create materialized view public.manufacturer_facets as
  select manufacturer_slug as slug, min(manufacturer) as name, count(*)::int as product_count
  from public.products
  where manufacturer_slug <> ''
  group by manufacturer_slug;
create unique index on public.manufacturer_facets (slug);

create materialized view public.category_facets as
  select category_slug as slug, min(category) as name, count(*)::int as product_count
  from public.products
  where category_slug is not null
  group by category_slug;
create unique index on public.category_facets (slug);

create or replace function public.refresh_catalog_facets()
returns void
language sql
security definer
set search_path = ''
as $$
  refresh materialized view concurrently public.manufacturer_facets;
  refresh materialized view concurrently public.category_facets;
$$;
revoke execute on function public.refresh_catalog_facets() from public, anon, authenticated;

-- RLS -----------------------------------------------------------------
alter table public.products       enable row level security;
alter table public.fault_codes    enable row level security;
alter table public.quote_requests enable row level security;

create policy "public read products"    on public.products    for select to anon, authenticated using (true);
create policy "public read fault_codes" on public.fault_codes for select to anon, authenticated using (true);
-- Insert only: there is no select policy, so never chain .select() after insert.
create policy "public insert quotes"    on public.quote_requests for insert to anon, authenticated with check (status = 'new');
-- Catalog writes are service-role only (no anon write policies).

grant select on public.manufacturer_facets, public.category_facets to anon, authenticated;

